/**
 * The benchmark runner: `npm run bench`.
 *
 * Runs every benchmark in sequence and writes `bench/results.md`. Sequentially and never in
 * parallel, which costs wall-clock time and buys the only thing that matters here: two
 * benchmarks sharing a machine measure each other, and the file-store numbers in particular
 * would become a measurement of whatever else happened to be fsyncing at the time.
 *
 * The report is generated rather than hand-written. A hand-written results file drifts from
 * the code the moment either changes, and the drift is invisible — the numbers still look
 * like numbers. Generating it means a stale report is impossible: it either describes this
 * run or it does not exist.
 *
 * Order matters in one place. The append benchmark measures the cost of a durable append,
 * and the end-to-end benchmark uses that figure to extrapolate what a file-backed
 * deployment would pay, so it runs second and is handed the measured value rather than a
 * constant.
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { environment, ms, type Section } from './harness.js';
import { cleanUp, scratchRoot } from './stores.js';
import * as appendBench from './append.js';
import * as contentionBench from './contention.js';
import * as e2eBench from './e2e.js';
import * as projectionBench from './projection.js';
import * as recoveryBench from './recovery.js';

const OUTPUT = fileURLToPath(new URL('./results.md', import.meta.url));

async function main(): Promise<void> {
  const started = Date.now();
  const root = await scratchRoot();
  const env = environment(root);

  const sections: Section[] = [];
  const log = (message: string): void => {
    process.stderr.write(`${message}\n`);
  };

  log('1/5 projection');
  sections.push(await projectionBench.run());

  log('2/5 append throughput');
  const append = await appendBench.run({ root });
  sections.push(append.section);

  log('3/5 contention');
  sections.push(await contentionBench.run({ root }));

  log('4/5 recovery');
  sections.push(await recoveryBench.run({ root }));

  log('5/5 end-to-end latency');
  sections.push(await e2eBench.run({ filePerAppendMs: append.filePerAppendMs }));

  await cleanUp();

  const elapsedS = ((Date.now() - started) / 1000).toFixed(0);
  const report = [
    '# Benchmarks',
    '',
    'Generated by `npm run bench` (`bench/run.ts`). Every number below was measured on the',
    'run that produced this file; nothing here is typed in by hand, which is the only way a',
    'results file stays true after the code changes under it.',
    '',
    '## What was measured on',
    '',
    `| | |`,
    `| --- | --- |`,
    `| CPU | ${env.cpu} |`,
    `| cores | ${env.cores} |`,
    `| memory | ${env.memoryGb} GB |`,
    `| platform | ${env.platform} |`,
    `| Node | ${env.node} |`,
    `| file store on | ${env.storage} |`,
    `| run took | ${elapsedS} s |`,
    '',
    'The storage line matters more than any other: the file store fsyncs before resolving an',
    'append, so every durable number in this report is a measurement of that device. On a',
    'spinning disk they would be an order of magnitude worse, and on a device that lies about',
    'fsync they would be an order of magnitude better and would mean nothing.',
    '',
    '## How to read this',
    '',
    'Every figure is a median over several runs with the observed range and standard deviation',
    'beside it, written `median (min–max, sd)`. Where a range overlaps another row\'s range,',
    'the two configurations are not distinguishable by this benchmark and the text says so',
    'rather than picking the more flattering one. Timed regions are warmed up first — the',
    'first run of anything in V8 measures the optimizing compiler — and the warm-up runs are',
    'discarded.',
    '',
    'Unflattering results are reported as found. There are three in here worth naming up',
    'front: the fold is linear in history length with no snapshotting to bound it, the',
    'optimistic-concurrency conflict rate reaches (N-1)/N — 94% at sixteen schedulers — and a',
    `durable append costs ${ms(append.filePerAppendMs)} ms against microseconds in memory, which`,
    'is to say that durability, not event sourcing, is what the write path actually pays for.',
    '',
    'One caution about comparing *this* file against another run of the same benchmark: the',
    'fsync-bound numbers move by ten to twenty percent between whole-suite invocations on this',
    'machine, which is more than several of the effects being measured. The spread beside each',
    'figure is within one invocation, so rows are comparable with each other and less so with a',
    'different run.',
    '',
    ...sections.flatMap((section, i) => [`## ${i + 1}. ${section.title}`, '', section.body, '']),
  ].join('\n');

  await writeFile(OUTPUT, `${report.replace(/\n+$/, '')}\n`, 'utf8');
  log(`wrote ${OUTPUT} in ${elapsedS}s`);
}

await main();
